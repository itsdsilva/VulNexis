// Deterministic mission report: assemble all findings (and optionally recon)
// into a single markdown document. No LLM calls — the report is exactly what
// the evidence store contains, with oracle receipts quoted verbatim.

import {
  SEVERITY_ORDER,
  type Finding,
  type Mission,
  type Severity,
} from './missions';
import type { Recon } from './recon';

const SEVERITIES: Severity[] = ['critical', 'high', 'medium', 'low', 'info'];

function severityCounts(findings: Finding[]): Record<Severity, number> {
  const counts = { critical: 0, high: 0, medium: 0, low: 0, info: 0 } as Record<Severity, number>;
  for (const f of findings) counts[f.severity]++;
  return counts;
}

function findingBlock(f: Finding, index: number): string {
  const target = f.host + (f.port ? `:${f.port}` : '');
  const status = f.status ?? 'candidate';
  const lines = [
    `### ${index}. ${f.vuln}`,
    '',
    `- **Severity:** ${f.severity}`,
    `- **Target:** \`${target}\``,
    `- **Status:** ${status}${status === 'verified' ? ' (machine-oracle verified)' : ''}`,
  ];
  if (f.bugClass) lines.push(`- **Bug class:** ${f.bugClass}`);
  lines.push('', '**Evidence**', '', '```', (f.evidence || '(none captured)').slice(0, 4000), '```');
  if (f.recipe) {
    lines.push(
      '',
      '**Oracle recipe**',
      '',
      `- Kind: \`${f.recipe.kind}\``,
      `- Attack: \`${f.recipe.attack.slice(0, 400)}\``
    );
    if (f.recipe.control) lines.push(`- Control: \`${f.recipe.control.slice(0, 400)}\``);
    if (f.recipe.marker) lines.push(`- Marker: \`${f.recipe.marker}\``);
  }
  if (f.receipt) {
    lines.push(
      '',
      '**Proof receipt**',
      '',
      `- Verdict: **${f.receipt.verdict}**`,
      `- Oracle: \`${f.receipt.oracleKind}\``,
      `- Replay: ${f.receipt.replay.successes}/${f.receipt.replay.attempts}`,
      '',
      '```',
      (f.receipt.evidence.diff ?? f.receipt.evidence.response ?? '').slice(0, 2000),
      '```'
    );
  }
  return lines.join('\n');
}

export function buildMissionReport(mission: Mission, findings: Finding[], recon?: Recon): string {
  const sorted = [...findings].sort(
    (a, b) => SEVERITY_ORDER[a.severity] - SEVERITY_ORDER[b.severity] || a.host.localeCompare(b.host)
  );
  const counts = severityCounts(sorted);
  const verified = sorted.filter((f) => f.status === 'verified').length;
  const scope = [...mission.scope.domains, ...mission.scope.ips, ...mission.scope.wildcards];

  const out: string[] = [
    `# ${mission.name} — Security Assessment Report`,
    '',
    `- **Date:** ${new Date().toISOString().slice(0, 10)}`,
    `- **Kind:** ${mission.kind ?? 'pentest'}`,
    `- **Intensity:** ${mission.intensity ?? 'normal'}`,
    `- **Scope:** ${scope.length ? scope.map((s) => `\`${s}\``).join(', ') : '(none recorded)'}`,
    mission.scope.outOfScope.length
      ? `- **Out of scope:** ${mission.scope.outOfScope.map((s) => `\`${s}\``).join(', ')}`
      : '',
    '',
    '## Executive summary',
    '',
    `${sorted.length} finding${sorted.length === 1 ? '' : 's'} recorded, ${verified} verified by a machine oracle and ${
      sorted.length - verified
    } still candidate (unverified). Severity distribution: ` +
      SEVERITIES.map((s) => `${counts[s]} ${s}`).join(' · ') +
      '.',
    '',
    '## Findings overview',
    '',
    '| # | Severity | Target | Finding | Status |',
    '|---|----------|--------|---------|--------|',
    ...sorted.map((f, i) => {
      const target = f.host + (f.port ? `:${f.port}` : '');
      return `| ${i + 1} | ${f.severity} | \`${target}\` | ${f.vuln.replace(/\|/g, '\\|')} | ${
        f.status ?? 'candidate'
      } |`;
    }),
    '',
    '## Findings detail',
    '',
    ...(sorted.length
      ? sorted.map((f, i) => findingBlock(f, i + 1) + '\n')
      : ['_No findings recorded._', '']),
  ];

  if (recon && (recon.hosts.length || recon.ports.length || recon.endpoints.length)) {
    out.push('## Recon summary', '');
    if (recon.hosts.length) {
      out.push('| Host | IPs | Open ports | Services |', '|------|-----|-----------|----------|');
      for (const h of recon.hosts) {
        out.push(
          `| \`${h.host}\` | ${h.ips.join(', ') || '—'} | ${h.ports.map((p) => p.port).join(', ') || '—'} | ${
            h.ports.map((p) => p.service).filter(Boolean).join(', ') || '—'
          } |`
        );
      }
      out.push('');
    }
    if (recon.endpoints.length) {
      out.push('Discovered HTTP endpoints:', '');
      for (const ep of recon.endpoints.slice(0, 60)) {
        out.push(`- \`${ep.url}\`${ep.status ? ` — ${ep.status}` : ''}${ep.title ? ` — ${ep.title}` : ''}`);
      }
      out.push('');
    }
  }

  out.push(
    '---',
    '',
    '_Generated by VulNexis. Only test systems you are authorized to test. Candidate findings are not proven vulnerabilities; oracle receipts can be replayed against the live target._'
  );

  return out.filter((l) => l !== undefined).join('\n');
}

export function reportFilename(mission: Mission): string {
  return `${mission.name.replace(/[^\w.-]+/g, '_').slice(0, 60) || 'mission'}_report.md`;
}
